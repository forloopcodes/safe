"""Train, evaluate, and export the installer classifier.

Steps:
  1. Load data/features.csv (stratified train/test split).
  2. Fit RandomForest and GradientBoosting; pick the model with the best F1 subject
     to a high-precision (low false-positive) preference.
  3. Emit figures: confusion matrix, ROC curve, SHAP summary.
  4. Choose an operating threshold that keeps the benign false-positive rate low.
  5. Export the chosen model to pure Rust (src/ml_model.rs) via m2cgen, and verify
     Python/Rust probability parity on sample rows.

Run:  python ml/train.py
"""
import json
import pathlib
import subprocess
import tempfile

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import shap
from sklearn.ensemble import GradientBoostingClassifier, RandomForestClassifier
from sklearn.metrics import (auc, confusion_matrix, f1_score,
                             precision_score, recall_score, roc_curve)
from sklearn.model_selection import train_test_split

import m2cgen as m2c

ROOT = pathlib.Path(__file__).parent
REPO = ROOT.parent
DATA = REPO / "data"
FIG = ROOT / "figures"
MODEL_RS = REPO / "src" / "ml_model.rs"
SEED = 1706


def load():
    df = pd.read_csv(DATA / "features.csv")
    y = df["label"].to_numpy()
    X = df.drop(columns=["label"])
    return X, y, list(X.columns)


def evaluate(model, Xte, yte):
    proba = model.predict_proba(Xte)[:, 1]
    pred = (proba >= 0.5).astype(int)
    return {
        "precision": precision_score(yte, pred),
        "recall": recall_score(yte, pred),
        "f1": f1_score(yte, pred),
        "proba": proba,
    }


def pick_threshold(y, proba, max_fpr=0.02):
    """Lowest threshold whose benign false-positive rate stays under max_fpr,
    breaking ties toward higher recall."""
    best_t, best_recall = 0.5, -1.0
    for t in np.linspace(0.1, 0.95, 86):
        pred = (proba >= t).astype(int)
        tn = int(((pred == 0) & (y == 0)).sum())
        fp = int(((pred == 1) & (y == 0)).sum())
        fpr = fp / max(tn + fp, 1)
        rec = recall_score(y, pred) if pred.sum() else 0.0
        if fpr <= max_fpr and rec > best_recall:
            best_recall, best_t = rec, t
    return round(float(best_t), 3)


def confusion_fig(y, pred, path):
    cm = confusion_matrix(y, pred)
    fig, ax = plt.subplots(figsize=(4.2, 3.8))
    ax.imshow(cm, cmap="BuGn")
    ax.set_xticks([0, 1], ["benign", "malicious"])
    ax.set_yticks([0, 1], ["benign", "malicious"])
    ax.set_xlabel("predicted"); ax.set_ylabel("actual")
    ax.set_title("Confusion matrix (test set)")
    for i in range(2):
        for j in range(2):
            ax.text(j, i, cm[i, j], ha="center", va="center",
                    color="white" if cm[i, j] > cm.max() / 2 else "black", fontsize=14)
    fig.tight_layout(); fig.savefig(path, dpi=150); plt.close(fig)


def roc_fig(y, proba, path):
    fpr, tpr, _ = roc_curve(y, proba)
    fig, ax = plt.subplots(figsize=(4.6, 3.9))
    ax.plot(fpr, tpr, color="#2e7d32", lw=2, label=f"AUC = {auc(fpr, tpr):.3f}")
    ax.plot([0, 1], [0, 1], "--", color="#999", lw=1)
    ax.set_xlabel("false positive rate"); ax.set_ylabel("true positive rate")
    ax.set_title("ROC curve"); ax.legend(loc="lower right")
    fig.tight_layout(); fig.savefig(path, dpi=150); plt.close(fig)


def shap_fig(model, X, path):
    sample = X.sample(min(300, len(X)), random_state=SEED)
    explainer = shap.TreeExplainer(model)
    sv = explainer.shap_values(sample)
    vals = sv[1] if isinstance(sv, list) else (sv[..., 1] if sv.ndim == 3 else sv)
    plt.figure()
    shap.summary_plot(vals, sample, show=False, max_display=15, plot_size=(7.5, 6))
    plt.title("SHAP feature impact (malicious class)")
    plt.tight_layout(); plt.savefig(path, dpi=150, bbox_inches="tight"); plt.close()


def export_rust(model, name, threshold, feature_names, importances):
    code = m2c.export_to_rust(model).replace("fn score(", "pub fn score(")
    imp = ", ".join(f"{v:.6}" for v in importances)
    names = ", ".join(f'"{n}"' for n in feature_names)
    body = "\n".join("    " + line for line in code.splitlines())
    header = f"""// Generated by ml/train.py via m2cgen — do not edit by hand.
// Pure-Rust inference for the installer classifier ({name}); no runtime dependency.
// Regenerate with: python ml/train.py

#![allow(clippy::all, clippy::pedantic, dead_code, unused_parens, unused_variables)]

pub const MODEL_NAME: &str = "{name}";
pub const THRESHOLD: f64 = {threshold};
pub const FEATURE_NAMES: &[&str] = &[{names}];
pub const IMPORTANCES: &[f64] = &[{imp}];

/// Malicious-class probability at index 1, benign at index 0.
pub fn score(input: &[f64]) -> [f64; 2] {{
    let out = generated::score(input.to_vec());
    [out[0], out.get(1).copied().unwrap_or(0.0)]
}}

mod generated {{
    #![allow(clippy::all, dead_code, unused_parens)]
{body}
}}
"""
    MODEL_RS.write_text(header)
    return code


def parity_check(model, code, Xte):
    """Compile the generated score fn and compare to sklearn on sample rows."""
    rows = Xte.iloc[:5].to_numpy()
    py = model.predict_proba(rows)[:, 1]
    literals = ",\n        ".join(
        "vec![" + ", ".join(f"{v:.10}_f64" for v in row) + "]" for row in rows)
    harness = code + f"""
fn main() {{
    let rows: Vec<Vec<f64>> = vec![
        {literals}
    ];
    for r in rows {{ let o = score(r); println!("{{:.10}}", o[1]); }}
}}
"""
    with tempfile.TemporaryDirectory() as d:
        src = pathlib.Path(d) / "m.rs"
        src.write_text(harness)
        exe = pathlib.Path(d) / "m"
        subprocess.run(["rustc", "-O", "-o", str(exe), str(src)], check=True,
                       capture_output=True)
        out = subprocess.run([str(exe)], capture_output=True, text=True, check=True)
    rust = [float(x) for x in out.stdout.split()]
    diffs = [abs(a - b) for a, b in zip(py, rust)]
    return py, rust, max(diffs)


def main():
    FIG.mkdir(exist_ok=True)
    X, y, names = load()
    Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.25, stratify=y, random_state=SEED)

    candidates = {
        "random_forest": RandomForestClassifier(
            n_estimators=120, max_depth=9, min_samples_leaf=2,
            class_weight="balanced", random_state=SEED, n_jobs=-1),
        "gradient_boosting": GradientBoostingClassifier(
            n_estimators=120, max_depth=3, learning_rate=0.1, random_state=SEED),
    }
    results = {}
    for key, model in candidates.items():
        model.fit(Xtr, ytr)
        m = evaluate(model, Xte, yte)
        results[key] = m
        print(f"{key:20s} precision={m['precision']:.3f} recall={m['recall']:.3f} f1={m['f1']:.3f}")

    # Only RandomForest exports to dependency-free Rust via m2cgen; GradientBoosting is
    # compared for reference but is not a deployable candidate here.
    exportable = {"random_forest"}
    # Prefer higher F1; on a near tie, prefer higher precision (fewer false positives).
    best_key = max((k for k in results if k in exportable),
                   key=lambda k: (round(results[k]["f1"], 3), round(results[k]["precision"], 3)))
    best = candidates[best_key]
    proba = results[best_key]["proba"]
    print(f"\nselected: {best_key}")

    threshold = pick_threshold(yte, proba)
    pred = (proba >= threshold).astype(int)
    print(f"threshold={threshold}  precision={precision_score(yte, pred):.3f} "
          f"recall={recall_score(yte, pred):.3f} f1={f1_score(yte, pred):.3f}")

    confusion_fig(yte, pred, FIG / "confusion_matrix.png")
    roc_fig(yte, proba, FIG / "roc_curve.png")
    shap_fig(best, Xtr, FIG / "shap_summary.png")
    print(f"figures -> {FIG}")

    code = export_rust(best, best_key, threshold, names, best.feature_importances_)
    py, rust, max_diff = parity_check(best, code, Xte)
    print(f"\nparity check (5 rows), max |py - rust| = {max_diff:.2e}")
    for p, r in zip(py, rust):
        print(f"  python={p:.6f}  rust={r:.6f}")

    (DATA / "model_report.json").write_text(json.dumps({
        "selected_model": best_key,
        "threshold": threshold,
        "n_train": int(len(Xtr)),
        "n_test": int(len(Xte)),
        "test_at_0.5": {k: round(float(results[best_key][k]), 4) for k in ("precision", "recall", "f1")},
        "test": {
            "precision": round(float(precision_score(yte, pred)), 4),
            "recall": round(float(recall_score(yte, pred)), 4),
            "f1": round(float(f1_score(yte, pred)), 4),
        },
        "candidates": {k: {m: round(float(v[m]), 4) for m in ("precision", "recall", "f1")}
                       for k, v in results.items()},
        "roc_auc": round(float(auc(*roc_curve(yte, proba)[:2])), 4),
        "parity_max_abs_diff": max_diff,
        "top_features": sorted(zip(names, best.feature_importances_.tolist()),
                               key=lambda t: -t[1])[:12],
    }, indent=2))
    print(f"report -> {DATA / 'model_report.json'}")


if __name__ == "__main__":
    main()
